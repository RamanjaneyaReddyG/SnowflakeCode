SELECT * FROM MODELING_TRAINING.STAR_LAB.DIM_STATUS;

CREATE OR REPLACE TABLE MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.FACT_SALES AS
SELECT
 SHA2(ORDER_LINE_ID,256) AS ORDER_LINE_SK, ORDER_LINE_ID, ORDER_ID,
 SHA2(CUSTOMER_ID,256) AS CUSTOMER_SK,
 SHA2(PRODUCT_ID,256) AS PRODUCT_SK,
 TO_NUMBER(TO_CHAR(ORDER_DATE,'YYYYMMDD')) AS DATE_SK,
 SHA2(ORDER_STATUS,256) AS STATUS_SK,
 QUANTITY, UNIT_PRICE_INR, SALES_AMOUNT_INR
FROM MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.RAW_SALES;

SELECT
  CAT.CATEGORY,
  REG.REGION,
  SUM(F.QUANTITY) AS UNITS_SOLD,
  SUM(F.SALES_AMOUNT_INR) AS TOTAL_SALES_INR
FROM MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.FACT_SALES F
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_PRODUCT P ON F.PRODUCT_SK=P.PRODUCT_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_SUBCATEGORY SC ON P.SUBCATEGORY_SK=SC.SUBCATEGORY_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_CATEGORY CAT ON SC.CATEGORY_SK=CAT.CATEGORY_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_CUSTOMER C ON F.CUSTOMER_SK=C.CUSTOMER_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_CITY CI ON C.CITY_SK=CI.CITY_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_STATE ST ON CI.STATE_SK=ST.STATE_SK
JOIN MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_REGION REG ON ST.REGION_SK=REG.REGION_SK
GROUP BY CAT.CATEGORY,REG.REGION
ORDER BY TOTAL_SALES_INR DESC;


