CREATE OR REPLACE TABLE MODELING_TRAINING.STAR_LAB.DIM_CUSTOMER AS
SELECT DISTINCT
  SHA2(CUSTOMER_ID,256) AS CUSTOMER_SK,
  CUSTOMER_ID, CUSTOMER_NAME, SEGMENT, CITY, STATE, REGION
FROM MODELING_TRAINING.STAR_LAB.RAW_SALES;

CREATE OR REPLACE TABLE MODELING_TRAINING.STAR_LAB.DIM_PRODUCT AS
SELECT DISTINCT
  SHA2(PRODUCT_ID,256) AS PRODUCT_SK,
  PRODUCT_ID, PRODUCT_NAME, BRAND, SUBCATEGORY, CATEGORY
FROM MODELING_TRAINING.STAR_LAB.RAW_SALES;

CREATE OR REPLACE TABLE MODELING_TRAINING.STAR_LAB.DIM_DATE AS
SELECT DISTINCT
  TO_NUMBER(TO_CHAR(ORDER_DATE,'YYYYMMDD')) AS DATE_SK,
  ORDER_DATE AS FULL_DATE,
  DAYNAME(ORDER_DATE) AS DAY_NAME,
  MONTHNAME(ORDER_DATE) AS MONTH_NAME,
  QUARTER(ORDER_DATE) AS QUARTER_NUMBER,
  YEAR(ORDER_DATE) AS YEAR_NUMBER
FROM MODELING_TRAINING.STAR_LAB.RAW_SALES;

create or replace table modeling_training.star_lab.dim_status as 
select distinct sha2(order_status, 256) as status_sk, order_status
from modeling_training.star_lab.raw_sales;

CREATE OR REPLACE TABLE MODELING_TRAINING.STAR_LAB.FACT_SALES AS
SELECT
  SHA2(ORDER_LINE_ID,256) AS ORDER_LINE_SK,
  ORDER_LINE_ID, ORDER_ID,
  SHA2(CUSTOMER_ID,256) AS CUSTOMER_SK,
  SHA2(PRODUCT_ID,256) AS PRODUCT_SK,
  TO_NUMBER(TO_CHAR(ORDER_DATE,'YYYYMMDD')) AS DATE_SK,
  SHA2(ORDER_STATUS,256) AS STATUS_SK,
  QUANTITY, UNIT_PRICE_INR, SALES_AMOUNT_INR
FROM MODELING_TRAINING.STAR_LAB.RAW_SALES;

select * from modeling_training.star_lab.fact_sales;


SELECT
  P.CATEGORY,
  C.REGION,
  SUM(F.QUANTITY) AS UNITS_SOLD,
  SUM(F.SALES_AMOUNT_INR) AS TOTAL_SALES_INR
FROM MODELING_TRAINING.STAR_LAB.FACT_SALES F
JOIN MODELING_TRAINING.STAR_LAB.DIM_CUSTOMER C ON F.CUSTOMER_SK=C.CUSTOMER_SK
JOIN MODELING_TRAINING.STAR_LAB.DIM_PRODUCT P ON F.PRODUCT_SK=P.PRODUCT_SK
GROUP BY P.CATEGORY,C.REGION
ORDER BY TOTAL_SALES_INR DESC;


