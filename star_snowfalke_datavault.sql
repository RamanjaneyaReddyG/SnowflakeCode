CREATE OR REPLACE TABLE MODELING_TRAINING.SNOWFLAKE_SCHEMA_LAB.DIM_SUBCATEGORY AS
SELECT DISTINCT
 SHA2(CONCAT_WS('|',SUBCATEGORY,CATEGORY),256) AS SUBCATEGORY_SK,
